def main() -> None:
    conn = board_data.get_db()
    try:
        row = conn.execute(
            "SELECT COUNT(*) AS c FROM posts WHERE nickname = ? AND pinned = 0",
            (OPERATOR_NICKNAME,),
        ).fetchone()
        already_posted = row["c"]
    finally:
        conn.close()

    if already_posted >= len(POSTS):
        print(f"이미 {len(POSTS)}개 글을 모두 게시했습니다. 새 글감이 없어 건너뜁니다.")
        return

    title, content = POSTS[already_posted]
    password = secrets.token_urlsafe(16)  # 관리자 마스터 비밀번호로 언제든 지울 수 있어 별도 보관 불필요
    post_id = board_data.create_post(OPERATOR_NICKNAME, password, title, content, "0.0.0.0")
    print(f"posted #{post_id}: {title}")


if __name__ == "__main__":
    main()
